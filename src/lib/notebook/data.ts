// Pre-baked physics equations for the notebook, grouped by topic.
//
// Every entry must parse with parseEquation(), load into the visual editor, and reproduce its
// `expect` value from its `example` inputs (see test/notebook.test.ts). `expect` is an
// independently known reference value (Earth's escape velocity, the GEO period, ...), not
// something copied from the evaluator, so the tests also catch a wrong formula.
//
// Conventions:
// - SI units throughout.
// - Physical constants are written as numbers so functions only take the inputs that vary:
//   G = 6.674·10⁻¹¹, c = 299792458, g₀ = 9.80665, σ = 5.670374·10⁻⁸, R = 8.314,
//   k_B = 1.380649·10⁻²³, h = 6.62607015·10⁻³⁴.
// - Eccentricity is `ecc`, because `e` always means Euler's number.
// - Mass flow rate is `mdot` (the parser has no \dot accent).

export interface NotebookEntry {
  /** Stable id, unique across the notebook. */
  id: string;
  title: string;
  /** Equation source, in the syntax the editor accepts. */
  src: string;
  /** One sentence on what it computes. */
  about: string;
  /** Meaning and unit of every parameter, keyed by parameter name as the parser reports it. */
  vars: Record<string, string>;
  /** Realistic inputs, preloaded into the Evaluate panel. Keys match `vars`. */
  example: Record<string, number>;
  /** Reference result for `example`. */
  expect: number;
  /** Relative tolerance for `expect` (default 1e-3). */
  tol?: number;
  /** What the example describes, shown next to it. */
  exampleNote?: string;
}

export interface NotebookTopic {
  id: string;
  title: string;
  entries: NotebookEntry[];
}

